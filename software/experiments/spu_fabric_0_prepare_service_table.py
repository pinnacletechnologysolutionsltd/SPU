#!/usr/bin/env python3
"""Freeze isolated candidate service cycles before contention evaluation."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from software.experiments.spu_fabric_0_scheduler_engine import simulate
from software.experiments.spu_fabric_0_scheduler_io import canonical_bytes, digest, load_profile


def build(manifest_path: Path, timing_path: Path) -> dict:
    records, refs = load_profile(manifest_path, "isolated", timing_path)
    by_id = {row["operation_id"]: row for row in records}
    if len(by_id) != len(records):
        raise ValueError("duplicate IDs in the isolated trace")
    tables = {"A": {}, "B": {}, "C": {}}
    for row in records:
        opid, client = row["operation_id"], row["client"]
        if client == "d4":
            continue
        else:
            tables["A"][opid] = refs["intrinsic"][opid]
    for candidate in ("B", "C"):
        for row in records:
            if row["client"] == "d4":
                continue
            isolated = dict(row, offered_cycle=0, client_order=0, profile="service-table")
            run = simulate(candidate, "service-table", [isolated],
                           {row["operation_id"]: refs["intrinsic"][row["operation_id"]]},
                           include_operation_rows=True)
            service = run["operation_rows"][row["operation_id"]]["service_cycles"]
            tables[candidate][row["operation_id"]] = service
    return {
        "schema": "spu-fabric-0-candidate-service-v1",
        "manifest_sha256": digest(manifest_path),
        "timing_table_sha256": digest(timing_path),
        "schedule_draft_sha256": digest(ROOT / "spu_strategy/contract_spu_fabric_0_phase1b_schedule_model_draft_2026-10-15.md"),
        "schedule_acceptance_sha256": digest(ROOT / "spu_strategy/contract_spu_fabric_0_phase1b_schedule_acceptance_2026-10-15.md"),
        "scheduler_engine_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_engine.py"),
        "scheduler_ops_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_ops.py"),
        "scheduler_accept_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_accept.py"),
        "scheduler_resources_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_resources.py"),
        "scheduler_report_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_report.py"),
        "scheduler_io_sha256": digest(ROOT / "software/experiments/spu_fabric_0_scheduler_io.py"),
        "service_definition": "accept-to-completion with no competing client; excludes ingress queue wait",
        "client_constants": {"d4_cycles": 1},
        "operation_count": len(records),
        "entries": tables,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path,
                        default=ROOT / "fixtures/spu_fabric_0/manifest.json")
    parser.add_argument("--timing-table", type=Path,
                        default=ROOT / "fixtures/spu_fabric_0/phase1b_timing_table.json")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    payload = canonical_bytes(build(args.manifest, args.timing_table))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.exists():
        previous = hashlib.sha256(args.output.read_bytes()).hexdigest()
        if previous != "1c3763acc0d2bb8a80bbb43fff18ea3a1671333cd5fa06b67786baab23b91d60":
            raise SystemExit("refusing to replace an artifact not generated by the first preparation pass")
        args.output.write_bytes(payload)
    else:
        with args.output.open("xb") as stream:
            stream.write(payload)
    print(json.dumps({"output": str(args.output),
                      "sha256": hashlib.sha256(payload).hexdigest(),
                      "candidates": 3,
                      "operations_per_candidate": 288794}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
