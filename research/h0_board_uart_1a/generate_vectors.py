#!/usr/bin/env python3
"""Generate serial stimulus using the committed host frame encoder."""
import importlib.util
from pathlib import Path
import struct
import sys
p=Path('research/h0_uart_1c/host_loader.py')
spec=importlib.util.spec_from_file_location('host_loader',p);host=importlib.util.module_from_spec(spec);spec.loader.exec_module(host)
def words(which):
 return [0x7000000000000100 if not which else 0x7000000000000200,0x7000010000000000,0x7000020000000200 if not which else 0x7000020000000100,0x7000030000000000,0x7000040000000300 if not which else 0x7000040000000200,0x7000050000000000,0x7100000000000000,0x7300000000000000]+[0x7200000000000000+(i<<40) for i in range(6)]
def load(which,bad):
 crc=0x12345678 if bad else (0x750e4cad if which else 0xfde536c7)
 return host.frame(1,struct.pack('<I',crc))+b''.join(host.frame(1,bytes([i])+struct.pack('<Q',w)) for i,w in enumerate(words(which)))+host.frame(2)
stream=bytes.fromhex('a50201090000000000a5010300a700')
stream+=load(0,False)+host.frame(3)+host.frame(1,b'\0'*4)+host.frame(4)+host.frame(5)
stream+=load(1,True)+load(1,False)+host.frame(3)+host.frame(4)+host.frame(5)+host.frame(3)+bytes.fromhex('a50103')+host.frame(4)
out=Path(sys.argv[1]);out.write_text(''.join(f'{x:02x}\n' for x in stream));print('host-generated bytes',len(stream))
